//! MCP resources derived from the caller-visible tool contract.
//!
//! Both resources are pure projections of
//! [`super::tools::visible_tool_contract_with_capabilities`]: the same
//! grant-filtered contract that backs `tools/list` and the capabilities
//! endpoint. A resource therefore never names a tool the caller cannot see,
//! and its bytes are deterministic for unchanged visibility and schemas.

